def _arena(
    name, tagline, *,
    sky, floor_a, floor_b, grid, wall, hazard, boost,
    walls=(), hazards=(), boosts=(), items=(), coins=(), portals=(), sweepers=(),
    spawns=DEFAULT_SPAWNS, friction=0.982, wind=(0.0, 0.0), hop_scale=1.0,
    fog=0, hazard_name="HAZARD", music="rap1.wav",
):
    return {
        "name": name,
        "tagline": tagline,
        "sky": tuple(sky),
        "floor_a": tuple(floor_a),
        "floor_b": tuple(floor_b),
        "grid": tuple(grid),
        "wall": tuple(wall),
        "hazard": tuple(hazard),
        "boost": tuple(boost),
        "walls": tuple(walls),
        "hazards": tuple(hazards),
        "boosts": tuple(boosts),
        "items": tuple(items),
        "coins": tuple(coins),
        "portals": tuple(portals),
        "sweepers": tuple(sweepers),
        "spawns": tuple(spawns),
        "friction": float(friction),
        "wind": tuple(float(v) for v in wind),
        "hop_scale": float(hop_scale),
        "fog": int(fog),
        "hazard_name": str(hazard_name),
        "music": str(music),
    }


